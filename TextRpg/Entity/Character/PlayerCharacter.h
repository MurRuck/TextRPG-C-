    static constexpr int MAX_LEVEL = 10;

    std::string name;
    int maxHP = 200;
    int hp = 200;
    int mp = 100;
    int exp = 0;
    int attack = 30;
    int max_EXP = 100;
    int level = 1;
    int gold = 0;

    std::vector<std::unique_ptr<Item>> inventory;
    std::vector<Skill> skills;
    bool CanLevelUp() const;
    void LevelUp();
    bool IsCanBuy(int amount) const;
