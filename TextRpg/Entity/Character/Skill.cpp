#include "Skill.h"

#include <iostream>

#include "PlayerCharacter.h"

Skill::Skill(const std::string& name, int mpCost, int effectValue, SkillType type)
    : name(name), mpCost(mpCost), effectValue(effectValue), type(type)
{
}

const std::string& Skill::GetName() const
{
    return name;
}

int Skill::GetMpCost() const
{
    return mpCost;
}

int Skill::GetEffectValue() const
{
    return effectValue;
}

SkillType Skill::GetType() const
{
    return type;
}

int Skill::GetTotalDamage(int playerAttack) const
{
    if (type != SkillType::Attack)
        return 0;

    return playerAttack + effectValue;
}

bool Skill::CanUse(int currentMp) const
{
    return currentMp >= mpCost;
}

void Skill::Use(PlayerCharacter& playerCharacter) const
{
    switch (type)
    {
    case SkillType::Attack:
        UseAttackSkill(playerCharacter);
        break;
    case SkillType::Buff:
        UseBuffSkill(playerCharacter);
        break;
    case SkillType::Heal:
        UseHealSkill(playerCharacter);
        break;
    }
}

void Skill::UseAttackSkill(PlayerCharacter& playerCharacter) const
{
    std::cout << playerCharacter.GetName() << " 스킬 발동 " << name
        << "뜌땨뜌땨야 " << GetTotalDamage(playerCharacter.GetAttack()) << std::endl;
}

void Skill::UseBuffSkill(PlayerCharacter& playerCharacter) const
{
    playerCharacter.IncreaseAttack(effectValue);
    std::cout << playerCharacter.GetName() << " 사용 " << name
        << " " << effectValue << "만큼 개쌔졌다 도로" << std::endl;
}

void Skill::UseHealSkill(PlayerCharacter& playerCharacter) const
{
    playerCharacter.Heal(effectValue);
    std::cout << playerCharacter.GetName() << " 사용 " << name
        << " " << effectValue << "만큼 회복" << std::endl;
}

