void AsciiArt::Print(ArtType type)
{
    const std::vector<std::string>& art = GetArt(type);

    for (const std::string& line : art)
    {
        std::cout << line << std::endl;
    }
}

void AsciiArt::PlayAsciiAnimation(const std::vector<std::vector<std::string>>& frames, int repeatCount, int delayMs)
{
    if (frames.empty() || repeatCount <= 0 || delayMs < 0)
    {
        return;
    }

    for (int repeat = 0; repeat < repeatCount; ++repeat)
    {
        for (const std::vector<std::string>& frame : frames)
        {
            system("cls");

            for (const std::string& line : frame)
            {
                std::cout << line << std::endl;
            }

            std::this_thread::sleep_for(std::chrono::milliseconds(delayMs));
        }
    }
}

